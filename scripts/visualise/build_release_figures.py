def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def text(x: float, y: float, value: str, size: int = 18, color: str = INK,
         weight: int = 400, anchor: str = "start") -> str:
    return (f'<text x="{x:g}" y="{y:g}" fill="{color}" font-size="{size}" '
            f'font-weight="{weight}" text-anchor="{anchor}" '
            f'font-family="Arial, Helvetica, sans-serif">{escape(value)}</text>')


def rect(x: float, y: float, w: float, h: float, fill: str, radius: int = 0,
         stroke: str = "none", sw: int = 1) -> str:
    return (f'<rect x="{x:g}" y="{y:g}" width="{w:g}" height="{h:g}" '
            f'rx="{radius}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>')


def line(x1: float, y1: float, x2: float, y2: float, color: str = STROKE,
         sw: int = 2, extra: str = "") -> str:
    return (f'<line x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}" '
            f'stroke="{color}" stroke-width="{sw}" {extra}/>')


def svg(w: int, h: int, title: str, desc: str, elements: list[str]) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="0 0 {w} {h}" role="img" aria-labelledby="title desc">\n'
            f'<title id="title">{escape(title)}</title>\n'
            f'<desc id="desc">{escape(desc)}</desc>\n'
            + "\n".join(elements) + "\n</svg>\n")


def icon_document(x: int, y: int, color: str) -> str:
    return (f'<path d="M{x} {y}h24l8 8v35h-32z M{x+24} {y}v8h8" '
            f'fill="none" stroke="{color}" stroke-width="2.5"/>'
            + line(x+6, y+18, x+25, y+18, color, 2)
            + line(x+6, y+25, x+25, y+25, color, 2))


def icon_review(x: int, y: int, color: str) -> str:
    return (f'<circle cx="{x+16}" cy="{y+17}" r="13" fill="none" '
            f'stroke="{color}" stroke-width="2.5"/>'
            + line(x+26, y+27, x+39, y+40, color, 3))


def icon_network(x: int, y: int, color: str) -> str:
    nodes = [(x+6,y+24),(x+25,y+6),(x+43,y+24),(x+25,y+43)]
    out = [line(*nodes[0], *nodes[1], color),line(*nodes[1], *nodes[2], color),
           line(*nodes[2], *nodes[3], color),line(*nodes[3], *nodes[0], color)]
    out += [f'<circle cx="{a}" cy="{b}" r="4.5" fill="{NAVY}" '
            f'stroke="{color}" stroke-width="2"/>' for a,b in nodes]
    return "".join(out)


def icon_table(x: int, y: int, color: str) -> str:
    return (rect(x,y,43,39,"none",4,color,2)
            +line(x,y+13,x+43,y+13,color,2)
            +line(x+21,y+13,x+21,y+39,color,2)
            +line(x,y+26,x+43,y+26,color,2))


