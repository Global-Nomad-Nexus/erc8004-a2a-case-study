"""Build the public, editable SVG figures from tracked result tables.

No manuscript, network service, hosted model, or third-party Python package is
needed. Run ``python3 scripts/visualise/build_release_figures.py`` from anywhere.
Use ``--check`` to compare generated bytes with the checked-in release assets.
"""

