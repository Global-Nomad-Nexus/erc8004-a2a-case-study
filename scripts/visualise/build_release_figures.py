def read_r1() -> dict[str, tuple[float,float]]:
    with (ROOT/R1).open(newline="",encoding="utf-8") as f:
        return {r["Metric"]:(float(r["ERC-8004"]),float(r["Google A2A (full)"]))
                for r in csv.DictReader(f)
                if r["Metric"] in {"Nodes", "Gini(degree)", "Giant component ratio"}}


def read_r2() -> dict[str, dict[str,str]]:
    with (ROOT/R2).open(newline="",encoding="utf-8") as f:
        return {r["case"]:r for r in csv.DictReader(f)}


