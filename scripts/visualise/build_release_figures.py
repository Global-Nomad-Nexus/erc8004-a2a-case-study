def bootstrap() -> str:
    with (ROOT/BOOT).open(newline="",encoding="utf-8") as f:
        rows=list(csv.DictReader(f))
    labels={"Technical":"Technical","Governance-Principle":"Governance principles",
            "Economic":"Economic","Process":"Process","Off-topic":"Off-topic"}
    lo,hi=-13.0,13.0
    def xx(v:float)->float:return 405+(v-lo)/(hi-lo)*690
    e=[rect(0,0,1200,740,NAVY),
       text(65,72,"Equal-size resampling qualifies the discourse contrast",32,INK,700),
       text(65,108,"A2A minus ERC-8004 · percentage points · 2,000 bootstrap resamples",17,MUTED),
       rect(405,166,690,416,PANEL,12),line(xx(0),166,xx(0),582,AMBER,2),
       text(xx(0),151,"No difference",16,AMBER,anchor="middle")]
    for i,row in enumerate(rows):
        y=209+i*78
        mean=100*float(row["mean_difference_a2a_minus_erc"])
        low=100*float(row["ci95_low"]);high=100*float(row["ci95_high"])
        e += [text(66,y+7,labels[row["argument_type"]],20,INK,600),
              line(xx(low),y,xx(high),y,CYAN,6),line(xx(low),y-11,xx(low),y+11,CYAN,2),
              line(xx(high),y-11,xx(high),y+11,CYAN,2),
              f'<circle cx="{xx(mean):.1f}" cy="{y}" r="8" fill="{GREEN}" '
              f'stroke="{NAVY}" stroke-width="2"/>',
              text(1107,y+6,f"{mean:+.1f}",17,INK,700)]
    e += [line(405,593,1095,593,MUTED,1)]
    for tick in (-10,-5,0,5,10):
        e += [line(xx(tick),589,xx(tick),600,MUTED,1),text(xx(tick),625,f"{tick:+d}",15,MUTED,anchor="middle")]
    e += [text(65,673,"All displayed 95% intervals touch or cross zero; uncertainty is from record resampling only.",17,AMBER),
          text(65,701,"Each resample uses 142 records per case. This does not balance platform maturity or organizational resources.",16,MUTED)]
    return svg(1200,740,"Equal-size bootstrap intervals for argument categories",
               "Point estimates and 95 percent intervals for five A2A minus ERC-8004 argument-type shares. Each bootstrap draws 142 records per case, 2000 times. All intervals include or touch zero.",e)


def build() -> dict[str,str]:
    return {"hero.svg":hero(),"participation-inequality.svg":participation(),
            "scope-connectivity.svg":connectivity(),"argument-bootstrap.svg":bootstrap()}


def manifest(outputs:dict[str,str]) -> str:
    cases={
      "hero.svg":("conceptual",[],"Governance architectures and evidence pipeline; schematic, not a measured effect."),
      "participation-inequality.svg":("descriptive",[R1],"Public-network degree Gini; different actor counts."),
      "scope-connectivity.svg":("descriptive",[R1,R2],"R1 and R2 differ in corpus and network construction; no causal transition."),
      "argument-bootstrap.svg":("descriptive",[BOOT],"Equal-size record resampling; not a matched organizational comparison.")}
    entries=[]
    for name,content in outputs.items():
        klass,inputs,boundary=cases[name]
        entries.append({"file":name,"caption_evidence_class":klass,
                        "reader_task":"framing" if name=="hero.svg" else "evidence",
                        "source_code":"scripts/visualise/build_release_figures.py",
                        "inputs":[{"path":str(p),"sha256":sha(ROOT/p)} for p in inputs],
                        "svg_sha256":hashlib.sha256(content.encode("utf-8")).hexdigest(),
                        "alt_text":({"hero.svg":"Comparison of ERC-8004 and A2A authority paths, three descriptive evidence themes, and a six-stage reproducibility pathway.",
                                     "participation-inequality.svg":"Two bars show R1 public-network degree Gini: ERC-8004 0.804 and A2A 0.779.",
                                     "scope-connectivity.svg":"Separate R1 and R2 panels show different giant-component ratios for ERC and A2A under different corpus boundaries.",
                                     "argument-bootstrap.svg":"Five point estimates and 95 percent bootstrap intervals for A2A minus ERC-8004 argument shares; all intervals touch or cross zero."}[name]),
                        "interpretation_boundary":boundary})
    return json.dumps({"schema_version":1,"command":"python3 scripts/visualise/build_release_figures.py",
                       "palette":{"background":NAVY,"ink":INK,"ERC":CYAN,"A2A":GREEN,"boundary":AMBER},
                       "graphics_inventory":{"document":"source and proposals","magnifier":"review and checking",
                                             "network":"interactions and deployment","table":"archived and result data"},
                       "figures":entries},indent=2,ensure_ascii=False)+"\n"


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true",help="Compare with checked-in SVGs and manifest")
    args=parser.parse_args()
    outputs=build();outputs["manifest.json"]=manifest(outputs)
    if args.check:
        drift=[name for name,content in outputs.items() if not (OUT/name).is_file() or
               (OUT/name).read_text(encoding="utf-8")!=content]
        if drift:raise SystemExit("Figure release drift: "+", ".join(drift))
        print("PASS: four vector assets and their provenance manifest match tracked tables")
        return 0
    OUT.mkdir(parents=True,exist_ok=True)
    for name,content in outputs.items():(OUT/name).write_text(content,encoding="utf-8")
    print("Built:",", ".join(outputs))
    return 0


if __name__=="__main__":raise SystemExit(main())
